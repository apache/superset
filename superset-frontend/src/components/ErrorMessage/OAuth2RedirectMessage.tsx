import { useEffect, useRef } from 'react';

import { useDispatch, useSelector } from 'react-redux';
import { QueryEditor, SqlLabRootState } from 'src/SqlLab/types';
import { ExplorePageState } from 'src/explore/types';
import { RootState } from 'src/dashboard/types';
import { reRunQuery } from 'src/SqlLab/actions/sqlLab';
import { triggerQuery } from 'src/components/Chart/chartAction';
import { onRefresh } from 'src/dashboard/actions/dashboardState';
import { UNSAVED_CHART_ID } from 'src/explore/constants';
import { QueryResponse, t } from '@superset-ui/core';

import type { ErrorMessageComponentProps } from './types';
import { ErrorAlert } from './ErrorAlert';

const OAUTH_CHANNEL_NAME = 'oauth';
const OAUTH_STORAGE_EVENT_KEY = 'oauth2_auth_complete';

interface OAuth2RedirectExtra {
  url: string;
  tab_id: string;
}

/*
 * Component for starting OAuth2 dance.
 *
 * When a user without credentials tries to access a database that supports OAuth2, the
 * backend will raise an exception with the custom error `OAUTH2_REDIRECT`. This will
 * cause the frontend to display this component, which informs the user that they need
 * to authenticate in order to access the data.
 *
 * The component has a URL that is used to start the OAuth2 dance for the given
 * database. When the user clicks the link a new browser tab will open, where they can
 * authorize Superset to access the data. Once authorization is successful the user will
 * be redirected back to Superset, and their personal access token is stored, so it can
 * be used in subsequent connections. If a refresh token is also present in the response,
 * it will also be stored.
 *
 * After the token has been stored, the opened tab will broadcast a message to the
 * original tab and close itself. This component, running on the original tab, listens
 * for same-origin BroadcastChannel and storage notifications (it does not depend on
 * `window.opener`, which browsers sever when the identity provider sets cross-origin
 * opener policies) and re-runs the query for the user once it receives the success
 * message, be it in SQL Lab, Explore, or a dashboard. Both tabs share a "tab ID" (a
 * UUID generated by the backend) which is echoed back so the original tab only reacts
 * to its own OAuth2 flow.
 */
export function OAuth2RedirectMessage({
  error,
  source,
}: ErrorMessageComponentProps<OAuth2RedirectExtra>) {
  const { extra, level } = error;

  // state needed for re-running the SQL Lab query
  const queries = useSelector<
    SqlLabRootState,
    Record<string, QueryResponse & { inLocalStorage?: boolean }>
  >(state => state.sqlLab.queries);
  const queryEditors = useSelector<SqlLabRootState, QueryEditor[]>(
    state => state.sqlLab.queryEditors,
  );
  const tabHistory = useSelector<SqlLabRootState, string[]>(
    state => state.sqlLab.tabHistory,
  );
  const qe = queryEditors.find(
    qe => qe.id === tabHistory[tabHistory.length - 1],
  );
  const query = qe?.latestQueryId ? queries[qe.latestQueryId] : null;

  // state needed for triggering the chart in Explore
  const chartId = useSelector<ExplorePageState, number>(
    state =>
      state.explore?.slice?.slice_id ??
      state.explore?.form_data?.slice_id ??
      UNSAVED_CHART_ID,
  );

  // state needed for refreshing dashboard
  const chartList = useSelector<RootState, string[]>(state =>
    Object.keys(state.charts),
  );
  const dashboardId = useSelector<RootState, number | undefined>(
    state => state.dashboardInfo?.id,
  );

  const dispatch = useDispatch();

  // The listener below is keyed only on the tab ID; volatile Redux-derived values
  // are read from this ref so store churn (e.g. charts changing state while a
  // dashboard loads) never tears down the channel and opens a window in which a
  // completion message could be missed.
  const latestState = { source, query, chartId, chartList, dashboardId };
  const latestStateRef = useRef(latestState);
  latestStateRef.current = latestState;

  useEffect(() => {
    // Both the BroadcastChannel and the storage fallback may deliver the same
    // completion; only act on the first one that finds usable state.
    let handled = false;
    const handleOAuthComplete = (tabId?: string) => {
      if (tabId !== extra.tab_id || handled) {
        return;
      }
      const {
        source: src,
        query: q,
        chartId: cId,
        chartList: cList,
        dashboardId: dId,
      } = latestStateRef.current;
      if (src === 'sqllab' && q) {
        dispatch(reRunQuery(q));
      } else if (src === 'explore') {
        dispatch(triggerQuery(true, cId));
      } else if (src === 'dashboard') {
        dispatch(onRefresh(cList.map(Number), true, 0, dId));
      } else {
        return;
      }
      handled = true;
    };

    // BroadcastChannel may exist but throw at construction in restricted contexts;
    // the storage listener below still covers that case.
    let channel: BroadcastChannel | null = null;
    if (typeof BroadcastChannel !== 'undefined') {
      try {
        channel = new BroadcastChannel(OAUTH_CHANNEL_NAME);
        channel.onmessage = event => {
          handleOAuthComplete(event.data?.tabId);
        };
      } catch {
        channel = null;
      }
    }

    const handleStorage = (event: StorageEvent) => {
      if (event.key !== OAUTH_STORAGE_EVENT_KEY || !event.newValue) {
        return;
      }
      try {
        const message = JSON.parse(event.newValue) as { tabId?: string };
        handleOAuthComplete(message.tabId);
      } catch {
        // ignore malformed storage payloads
      }
    };
    window.addEventListener('storage', handleStorage);

    return () => {
      window.removeEventListener('storage', handleStorage);
      channel?.close();
    };
  }, [extra.tab_id, dispatch]);

  const body = (
    <p>
      This database uses OAuth2 for authentication. Please click the link above
      to grant Apache Superset permission to access the data. Your personal
      access token will be stored encrypted and used only for queries run by
      you.
    </p>
  );
  const subtitle = (
    <>
      You need to{' '}
      <a href={extra.url} target="_blank" rel="noreferrer">
        provide authorization
      </a>{' '}
      in order to run this operation.
    </>
  );

  return (
    <ErrorAlert
      errorType={t('Authorization needed')}
      message={subtitle}
      type={level}
      description={body}
    />
  );
}
